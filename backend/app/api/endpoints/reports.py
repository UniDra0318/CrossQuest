from typing import List, Dict, Any, Optional
from datetime import datetime, timezone
from fastapi import APIRouter, Depends, HTTPException, status, Request, Response
from sqlalchemy.orm import Session
from app.core.database import get_db
from app.models.entities import ClientCompany, TrainingRecord, Trainee, Certificate, User, AccessLog
from app.api.deps import get_current_user
from app.anomaly.detector import anomaly_detector
from app.services.pdf_generator import pdf_generator

router = APIRouter()

def _get_client_ip(request: Request) -> str:
    return request.client.host if request.client else "127.0.0.1"


@router.get("/assigned-companies")
def get_assigned_companies(
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
) -> List[Dict[str, Any]]:
    """Returns list of client companies with their assigned status for the current Account Manager (OI-04, SEC-10)."""
    if current_user.role != "account_manager":
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Client reports can only be accessed by Account Managers (OI-04)."
        )
    assigned_codes = current_user.assigned_client_accounts or []
    companies = db.query(ClientCompany).order_by(ClientCompany.name.asc()).all()
    result = []
    for comp in companies:
        record_count = db.query(TrainingRecord).filter(
            TrainingRecord.company_at_completion_id == comp.id,
            TrainingRecord.deleted_at == None
        ).count()
        completed_count = db.query(TrainingRecord).filter(
            TrainingRecord.company_at_completion_id == comp.id,
            TrainingRecord.deleted_at == None,
            TrainingRecord.status == "Completed"
        ).count()
        result.append({
            "id": comp.id,
            "code": comp.code,
            "name": comp.name,
            "industry": comp.industry,
            "is_assigned": comp.code in assigned_codes,
            "total_records": record_count,
            "completed_records": completed_count
        })
    return result


@router.get("/company/{company_code}")
def generate_client_report(
    company_code: str,
    request: Request,
    start_date: Optional[str] = None,
    end_date: Optional[str] = None,
    status_filter: Optional[str] = None,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
) -> Dict[str, Any]:
    """Generates an on-demand client-specific training report (FR-20, DAT-06, Section 3.8.4).
    
    Permissions (Table 17, OI-04):
    - Account Manager: permitted ONLY for currently assigned client companies.
    - Admin: permitted for oversight.
    - Other roles: denied.
    """
    company = db.query(ClientCompany).filter(ClientCompany.code == company_code.upper()).first()
    if not company:
        raise HTTPException(status_code=404, detail="Client company not found")

    client_ip = _get_client_ip(request)

    # Restrict strictly to Account Managers (OI-04, Table 17)
    if current_user.role != "account_manager":
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Client reports can only be generated by Account Managers (OI-04)."
        )

    # Scoping check: Account Manager can only generate for assigned client companies (SEC-10)
    if company.code not in (current_user.assigned_client_accounts or []):
        log = AccessLog(
            actor_user_id=current_user.id,
            actor_role=current_user.role,
            event_type="ACCESS_DENIED",
            resource_type="REPORT",
            company_id=company.id,
            outcome="DENIED",
            reason_code="OUT_OF_SCOPE",
            source_ip=client_ip,
            details={"target_company": company.code}
        )
        db.add(log)
        db.commit()
        anomaly_detector.record_out_of_scope_attempt(current_user, f"REPORT:{company.code}", company.code, db)
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail=f"Not authorized to generate reports for unassigned company '{company.code}'."
        )

    # Query training records for this client company under RLS / scoping logic
    query = (
        db.query(TrainingRecord, Trainee)
        .join(Trainee, TrainingRecord.trainee_id == Trainee.id)
        .filter(
            TrainingRecord.company_at_completion_id == company.id,
            TrainingRecord.deleted_at == None
        )
    )

    if status_filter and status_filter.upper() != "ALL":
        query = query.filter(TrainingRecord.status.ilike(status_filter))

    if start_date:
        try:
            sd = datetime.fromisoformat(start_date)
            query = query.filter(TrainingRecord.completion_date >= sd)
        except Exception:
            pass

    if end_date:
        try:
            ed = datetime.fromisoformat(end_date)
            query = query.filter(TrainingRecord.completion_date <= ed)
        except Exception:
            pass

    records = query.order_by(TrainingRecord.completion_date.desc().nullslast()).all()

    total_records = len(records)
    completed_count = sum(1 for r, _ in records if r.status == "Completed")
    avg_score = (
        sum((r.score or 0) for r, _ in records if r.score is not None) / max(1, total_records)
    )

    # Log report generation (SEC-12, Table 19)
    log = AccessLog(
        actor_user_id=current_user.id,
        actor_role=current_user.role,
        event_type="REPORT_GENERATED",
        resource_type="REPORT",
        company_id=company.id,
        outcome="SUCCESS",
        source_ip=client_ip,
        details={"company_code": company.code, "record_count": total_records}
    )
    db.add(log)
    db.commit()

    # Check for report bursts (R3-b)
    anomaly_detector.check_report_bursts(current_user, db)

    # Proposed layout (Section 3.8.4, OI-10): header + training, training date, trainee table
    return {
        "header": {
            "client_name": company.name,
            "client_code": company.code,
            "generated_at": datetime.now(timezone.utc).isoformat(),
            "generated_by_user": current_user.full_name,
            "user_role": current_user.role
        },
        "summary": {
            "total_records": total_records,
            "completed_trainings": completed_count,
            "average_score": round(avg_score, 2),
            "compliance_rate": f"{round((completed_count / max(1, total_records)) * 100, 1)}%"
        },
        "trainees": [
            {
                "record_id": r.id,
                "trainee_code": t.trainee_code,
                "trainee_name": f"{t.first_name} {t.last_name}",
                "course_name": r.course_name,
                "training_date": r.completion_date.strftime("%Y-%m-%d") if r.completion_date else "In progress",
                "status": r.status,
                "score": r.score
            }
            for r, t in records
        ]
    }


@router.get("/company/{company_code}/pdf")
def download_client_report_pdf(
    company_code: str,
    request: Request,
    start_date: Optional[str] = None,
    end_date: Optional[str] = None,
    status_filter: Optional[str] = None,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    """Generates and downloads the client-specific training report as an official PDF (ReportLab, OI-04).
    
    Permissions (OI-04): Strictly restricted to assigned Account Managers.
    """
    report_data = generate_client_report(
        company_code=company_code,
        request=request,
        start_date=start_date,
        end_date=end_date,
        status_filter=status_filter,
        db=db,
        current_user=current_user
    )

    pdf_bytes = pdf_generator.generate_client_report_pdf(report_data)

    return Response(
        content=pdf_bytes,
        media_type="application/pdf",
        headers={
            "Content-Disposition": f'attachment; filename="Training_Report_{company_code.upper()}.pdf"'
        }
    )
