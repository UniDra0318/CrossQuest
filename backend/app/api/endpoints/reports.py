router = APIRouter()

def _get_client_ip(request: Request) -> str:
    return request.client.host if request.client else "127.0.0.1"


@router.get("/assigned-companies")
def get_assigned_companies(
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
) -> List[Dict[str, Any]]:
    """Returns list of client companies with their assigned status for the current Account Manager (OI-04, SEC-10)."""
    if current_user.role not in ("account_manager", "admin", "finance"):
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Client reports can only be accessed by Account Managers, Administrators, and Finance (OI-04)."
        )
    assigned_codes = [c.code for c in db.query(ClientCompany).all()] if current_user.role in ("admin", "finance") else (current_user.assigned_client_accounts or [])
    companies = db.query(ClientCompany).order_by(ClientCompany.name.asc()).all()
    result = []
    for comp in companies:
        record_count = db.query(TrainingRecord).filter(
            TrainingRecord.company_at_completion_id == comp.id,
            TrainingRecord.deleted_at == None
        ).count()
        completed_count = db.query(TrainingRecord).filter(
            TrainingRecord.company_at_completion_id == comp.id,
            TrainingRecord.deleted_at == None,
            TrainingRecord.status == "Completed"
        ).count()
        result.append({
            "id": comp.id,
            "code": comp.code,
            "name": comp.name,
            "industry": comp.industry,
            "is_assigned": comp.code in assigned_codes,
            "total_records": record_count,
            "completed_records": completed_count
        })
    return result


@router.get("/company/{company_code}")
def generate_client_report(
    company_code: str,
    request: Request,
    start_date: Optional[str] = None,
    end_date: Optional[str] = None,
    status_filter: Optional[str] = None,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
) -> Dict[str, Any]:
    """Generates an on-demand client-specific training report (FR-20, DAT-06, Section 3.8.4).
    
    Permissions (Table 17, OI-04):
    - Account Manager: permitted ONLY for currently assigned client companies.
    - Admin: permitted for oversight.
    - Other roles: denied.
    """
    company = db.query(ClientCompany).filter(ClientCompany.code == company_code.upper()).first()
    if not company:
        raise HTTPException(status_code=404, detail="Client company not found")

    client_ip = _get_client_ip(request)

    # Restrict to Account Managers, Administrators, and Finance (OI-04, Table 17)
    if current_user.role not in ("account_manager", "admin", "finance"):
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Client reports can only be generated by Account Managers, Administrators, and Finance (OI-04)."
        )

    # Scoping check: Account Manager can only generate for assigned client companies (SEC-10)
    if current_user.role == "account_manager" and company.code not in (current_user.assigned_client_accounts or []):
        log = AccessLog(
            actor_user_id=current_user.id,
            actor_role=current_user.role,
            event_type="ACCESS_DENIED",
            resource_type="REPORT",
            company_id=company.id,
            outcome="DENIED",
            reason_code="OUT_OF_SCOPE",
            source_ip=client_ip,
            details={"target_company": company.code}
        )
        db.add(log)
        db.commit()
        anomaly_detector.record_out_of_scope_attempt(current_user, f"REPORT:{company.code}", company.code, db)
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail=f"Not authorized to generate reports for unassigned company '{company.code}'."
        )

    # Query training records for this client company under RLS / scoping logic
    query = (
        db.query(TrainingRecord, Trainee)
        .join(Trainee, TrainingRecord.trainee_id == Trainee.id)
        .filter(
            TrainingRecord.company_at_completion_id == company.id,
            TrainingRecord.deleted_at == None
        )
    )

    if status_filter and status_filter.upper() != "ALL":
        query = query.filter(TrainingRecord.status.ilike(status_filter))

    if start_date:
        try:
            sd = datetime.fromisoformat(start_date)
            query = query.filter(TrainingRecord.completion_date >= sd)
        except Exception:
            pass

    if end_date:
        try:
            ed = datetime.fromisoformat(end_date)
            query = query.filter(TrainingRecord.completion_date <= ed)
        except Exception:
            pass

    records = query.order_by(TrainingRecord.completion_date.desc().nullslast()).all()

    total_records = len(records)
    completed_count = sum(1 for r, _ in records if r.status == "Completed")
    avg_score = (
        sum((r.score or 0) for r, _ in records if r.score is not None) / max(1, total_records)
    )

    # Log report generation (SEC-12, Table 19)
    log = AccessLog(
        actor_user_id=current_user.id,
        actor_role=current_user.role,
        event_type="REPORT_GENERATED",
        resource_type="REPORT",
        company_id=company.id,
        outcome="SUCCESS",
        source_ip=client_ip,
        details={"company_code": company.code, "record_count": total_records}
    )
    db.add(log)
    db.commit()

    # Check for report bursts (R3-b)
    anomaly_detector.check_report_bursts(current_user, db)

    # Proposed layout (Section 3.8.4, OI-10): header + training, training date, trainee table
    return {
        "header": {
            "client_name": company.name,
            "client_code": company.code,
            "generated_at": datetime.now(timezone.utc).isoformat(),
            "generated_by_user": current_user.full_name,
            "user_role": current_user.role
        },
        "summary": {
            "total_records": total_records,
            "completed_trainings": completed_count,
            "average_score": round(avg_score, 2),
            "compliance_rate": f"{round((completed_count / max(1, total_records)) * 100, 1)}%"
        },
        "trainees": [
            {
                "record_id": r.id,
                "trainee_code": t.trainee_code,
                "trainee_name": f"{t.first_name} {t.last_name}",
                "course_name": r.course_name,
                "training_date": r.completion_date.strftime("%Y-%m-%d") if r.completion_date else "In progress",
                "status": r.status,
                "score": r.score
            }
            for r, t in records
        ]
    }


@router.get("/company/{company_code}/pdf")
def download_client_report_pdf(
    company_code: str,
    request: Request,
    start_date: Optional[str] = None,
    end_date: Optional[str] = None,
    status_filter: Optional[str] = None,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    """Generates and downloads the client-specific training report as an official PDF (ReportLab, OI-04).
    
    Permissions (OI-04): Strictly restricted to assigned Account Managers.
    """
    report_data = generate_client_report(
        company_code=company_code,
        request=request,
        start_date=start_date,
        end_date=end_date,
        status_filter=status_filter,
        db=db,
        current_user=current_user
    )

    pdf_bytes = pdf_generator.generate_client_report_pdf(report_data)

    return Response(
        content=pdf_bytes,
        media_type="application/pdf",
        headers={
            "Content-Disposition": f'attachment; filename="Training_Report_{company_code.upper()}.pdf"'
        }
    )

import csv
import io
import openpyxl
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side

@router.get("/company/{company_code}/csv")
def download_client_report_csv(
    company_code: str,
    request: Request,
    start_date: Optional[str] = None,
    end_date: Optional[str] = None,
    status_filter: Optional[str] = None,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    """Exports client-specific training report as CSV (FR-20, Table 17)."""
    report_data = generate_client_report(
        company_code=company_code,
        request=request,
        start_date=start_date,
        end_date=end_date,
        status_filter=status_filter,
        db=db,
        current_user=current_user
    )

    output = io.StringIO()
    writer = csv.writer(output)

    # Title & Metadata Header
    writer.writerow(["CrossQuest Enterprise Learning - Official Client Training Report"])
    writer.writerow(["Client Name", report_data["header"]["client_name"]])
    writer.writerow(["Client Code", report_data["header"]["client_code"]])
    writer.writerow(["Generated At (UTC)", report_data["header"]["generated_at"]])
    writer.writerow(["Generated By", f"{report_data['header']['generated_by_user']} ({report_data['header']['user_role']})"])
    writer.writerow([])

    # Executive Summary Metrics
    writer.writerow(["SUMMARY METRICS"])
    writer.writerow(["Total Records", report_data["summary"]["total_records"]])
    writer.writerow(["Completed Trainings", report_data["summary"]["completed_trainings"]])
    writer.writerow(["Average Score", f"{report_data['summary']['average_score']}%"])
    writer.writerow(["Compliance Rate", report_data["summary"]["compliance_rate"]])
    writer.writerow([])

    # Trainee Records Table
    writer.writerow(["TRAINEE TRAINING RECORDS"])
    writer.writerow(["Record ID", "Trainee Code", "Trainee Name", "Course Name", "Training Date", "Status", "Score"])

    for tr in report_data.get("trainees", []):
        score_val = f"{tr['score']}%" if tr["score"] is not None else "N/A"
        writer.writerow([
            tr["record_id"],
            tr["trainee_code"],
            tr["trainee_name"],
            tr["course_name"],
            tr["training_date"],
            tr["status"],
            score_val
        ])

    csv_bytes = output.getvalue().encode("utf-8-sig") # Include BOM for clean Excel viewing
    return Response(
        content=csv_bytes,
        media_type="text/csv",
        headers={
            "Content-Disposition": f'attachment; filename="Training_Report_{company_code.upper()}.csv"'
        }
    )


@router.get("/company/{company_code}/excel")
def download_client_report_excel(
    company_code: str,
    request: Request,
    start_date: Optional[str] = None,
    end_date: Optional[str] = None,
    status_filter: Optional[str] = None,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    """Exports client-specific training report as a formatted Excel workbook (FR-20, openpyxl)."""
    report_data = generate_client_report(
        company_code=company_code,
        request=request,
        start_date=start_date,
        end_date=end_date,
        status_filter=status_filter,
        db=db,
        current_user=current_user
    )

    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Training Summary"

    # Styling definitions
    navy_fill = PatternFill(start_color="00314D", end_color="00314D", fill_type="solid")
    gold_fill = PatternFill(start_color="D4AF37", end_color="D4AF37", fill_type="solid")
    gray_fill = PatternFill(start_color="F2F4F7", end_color="F2F4F7", fill_type="solid")
    white_bold = Font(name="Calibri", size=11, bold=True, color="FFFFFF")
    navy_title = Font(name="Calibri", size=16, bold=True, color="00314D")
    sub_title = Font(name="Calibri", size=10, italic=True, color="555555")
    bold_font = Font(name="Calibri", size=10, bold=True)
    regular_font = Font(name="Calibri", size=10)
    border_thin = Border(
        left=Side(style='thin', color='DDDDDD'),
        right=Side(style='thin', color='DDDDDD'),
        top=Side(style='thin', color='DDDDDD'),
        bottom=Side(style='thin', color='DDDDDD')
    )

    # Title
    ws.cell(row=1, column=1, value="CrossQuest Enterprise Learning - Client Training Report").font = navy_title
    ws.cell(row=2, column=1, value="Crossworks Training and Consulting Corp. · Confidential Enterprise Document").font = sub_title

    # Header info
    row = 4
    info_items = [
        ("Client Name:", report_data["header"]["client_name"]),
        ("Client Code:", report_data["header"]["client_code"]),
        ("Generated At:", report_data["header"]["generated_at"]),
        ("Generated By:", f"{report_data['header']['generated_by_user']} ({report_data['header']['user_role']})")
    ]
    for label, val in info_items:
        ws.cell(row=row, column=1, value=label).font = bold_font
        ws.cell(row=row, column=2, value=val).font = regular_font
        row += 1

    # Summary Metrics
    row += 1
    ws.cell(row=row, column=1, value="Summary Metrics").font = Font(name="Calibri", size=12, bold=True, color="00314D")
    row += 1

    metrics = [
        ("Total Records Enrolled", report_data["summary"]["total_records"]),
        ("Completed Trainings", report_data["summary"]["completed_trainings"]),
        ("Average Assessment Score", f"{report_data['summary']['average_score']}%"),
        ("Corporate Compliance Rate", report_data["summary"]["compliance_rate"])
    ]
    for lbl, mval in metrics:
        ws.cell(row=row, column=1, value=lbl).font = bold_font
        ws.cell(row=row, column=1).fill = gray_fill
        ws.cell(row=row, column=2, value=mval).font = regular_font
        row += 1

    # Table Header
    row += 2
    headers = ["Record ID", "Trainee Code", "Trainee Name", "Course Name", "Training Date", "Status", "Score"]
    for col_idx, h in enumerate(headers, 1):
        cell = ws.cell(row=row, column=col_idx, value=h)
        cell.fill = navy_fill
        cell.font = white_bold
        cell.alignment = Alignment(horizontal="center" if col_idx in (2, 5, 6, 7) else "left")

    table_start_row = row

    for tr in report_data.get("trainees", []):
        row += 1
        score_val = f"{tr['score']}%" if tr["score"] is not None else "—"
        row_values = [
            tr["record_id"],
            tr["trainee_code"],
            tr["trainee_name"],
            tr["course_name"],
            tr["training_date"],
            tr["status"],
            score_val
        ]
        for col_idx, val in enumerate(row_values, 1):
            c = ws.cell(row=row, column=col_idx, value=val)
            c.font = regular_font
            c.border = border_thin
            if col_idx in (2, 5, 6, 7):
                c.alignment = Alignment(horizontal="center")

    # Auto-adjust column widths
    for col in ws.columns:
        max_len = 0
        col_letter = openpyxl.utils.get_column_letter(col[0].column)
        for cell in col:
            val_str = str(cell.value or "")
            if len(val_str) > max_len and len(val_str) < 60:
                max_len = len(val_str)
        ws.column_dimensions[col_letter].width = max(max_len + 3, 12)

    buf = io.BytesIO()
    wb.save(buf)
    buf.seek(0)

    return Response(
        content=buf.getvalue(),
        media_type="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
        headers={
            "Content-Disposition": f'attachment; filename="Training_Report_{company_code.upper()}.xlsx"'
        }
    )


@router.get("/company/{company_code}/export")
def export_client_report(
    company_code: str,
    request: Request,
    format: str = "csv",
    start_date: Optional[str] = None,
    end_date: Optional[str] = None,
    status_filter: Optional[str] = None,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user)
):
    """Unified export endpoint supporting format=csv, format=excel/xlsx, and format=pdf (FR-20)."""
    fmt = format.lower().strip()
    if fmt in ("excel", "xlsx"):
        return download_client_report_excel(
            company_code=company_code,
            request=request,
            start_date=start_date,
            end_date=end_date,
            status_filter=status_filter,
            db=db,
            current_user=current_user
        )
    elif fmt == "pdf":
        return download_client_report_pdf(
            company_code=company_code,
            request=request,
            start_date=start_date,
            end_date=end_date,
            status_filter=status_filter,
            db=db,
            current_user=current_user
        )
    else:
        return download_client_report_csv(
            company_code=company_code,
            request=request,
            start_date=start_date,
            end_date=end_date,
            status_filter=status_filter,
            db=db,
            current_user=current_user
        )
